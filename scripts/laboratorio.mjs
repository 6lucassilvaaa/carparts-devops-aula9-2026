function run(args, expected = 0) {
  const result = spawnSync('git', args, {cwd:repo, encoding:'utf8'});
  out.push('$ git ' + args.join(' '), result.stdout || '', result.stderr || '');
  if(result.status !== expected) throw new Error(`git ${args[0]}: esperado ${expected}, recebido ${result.status}`);
  return result.stdout.trim();
}
